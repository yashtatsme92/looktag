#!/usr/bin/env python3
"""Build feed derivatives for public/looks/**/*.jpg.

Card images stay at or under 120 KB. Originals are left in place for detail
views. Outputs public/looks/feed/ and src/lib/media/feed-manifest.ts.
"""

from __future__ import annotations

import io
import os
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
LOOKS = ROOT / "public" / "looks"
FEED = LOOKS / "feed"
MANIFEST = ROOT / "src" / "lib" / "media" / "feed-manifest.ts"
LIMIT = 120_000

# (format, widths to try largest-first, quality high, quality low)
PLANS = (
    ("avif", (1200, 960, 800), 56, 34),
    ("webp", (800, 640), 78, 56),
    ("jpeg", (720, 640), 76, 58),
)


def encode(image: Image.Image, fmt: str, quality: int) -> bytes:
    buf = io.BytesIO()
    if fmt == "webp":
        image.save(buf, "WEBP", quality=quality, method=6)
    elif fmt == "avif":
        image.save(buf, "AVIF", quality=quality, speed=6)
    else:
        image.save(buf, "JPEG", quality=quality, optimize=True, progressive=True)
    return buf.getvalue()


def fit(image: Image.Image, fmt: str, q_hi: int, q_lo: int) -> tuple[int, bytes]:
    hi_bytes = encode(image, fmt, q_hi)
    if len(hi_bytes) <= LIMIT:
        return q_hi, hi_bytes
    lo, hi = q_lo, q_hi - 1
    best_q: int | None = None
    best: bytes | None = None
    while lo <= hi:
        mid = (lo + hi) // 2
        data = encode(image, fmt, mid)
        if len(data) <= LIMIT:
            best_q, best = mid, data
            lo = mid + 1
        else:
            hi = mid - 1
    if best is None or best_q is None:
        data = encode(image, fmt, q_lo)
        return q_lo, data
    return best_q, best


def resized(image: Image.Image, width: int) -> Image.Image:
    height = max(1, round(width * image.height / image.width))
    return image.resize((width, height), Image.Resampling.LANCZOS)


def sources_for(image: Image.Image, fmt: str, widths: tuple[int, ...], q_hi: int, q_lo: int):
    small = resized(image, 480)
    small_q, small_bytes = fit(small, fmt, q_hi, q_lo)
    chosen: list[tuple[int, int, bytes]] = [(480, small_q, small_bytes)]
    for width in widths:
        if width <= 480:
            continue
        large = resized(image, width)
        quality, data = fit(large, fmt, q_hi, q_lo)
        if len(data) <= LIMIT and quality >= q_lo:
            chosen.append((width, quality, data))
            break
    return chosen


def js_sources(items: list[tuple[int, str]]) -> str:
    parts = ", ".join("{ w: %d, url: %s }" % (width, json_str(url)) for width, url in items)
    return f"[{parts}]"


def json_str(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    if FEED.exists():
        for path in FEED.rglob("*"):
            if path.is_file():
                path.unlink()
    photos = sorted(
        path
        for path in LOOKS.rglob("*.jpg")
        if "feed" not in path.relative_to(LOOKS).parts
    )
    entries: list[str] = []
    worst = 0
    for path in photos:
        rel = path.relative_to(LOOKS).with_suffix("")
        image = Image.open(path).convert("RGB")
        src = "/looks/" + path.relative_to(LOOKS).as_posix()
        line_sources: dict[str, list[tuple[int, str]]] = {}
        for fmt, widths, q_hi, q_lo in PLANS:
            ext = "jpg" if fmt == "jpeg" else fmt
            built = sources_for(image, fmt, widths, q_hi, q_lo)
            urls: list[tuple[int, str]] = []
            for width, _quality, data in built:
                worst = max(worst, len(data))
                if len(data) > LIMIT:
                    raise SystemExit(f"{src} {fmt} {width}px is {len(data)} bytes")
                out = FEED / rel.parent / f"{rel.name}-{width}.{ext}"
                out.parent.mkdir(parents=True, exist_ok=True)
                out.write_bytes(data)
                url = "/looks/feed/" + out.relative_to(FEED).as_posix()
                urls.append((width, url))
            line_sources[fmt if fmt != "jpeg" else "jpeg"] = urls
        entries.append(
            "  %s: { w: %d, h: %d, avif: %s, webp: %s, jpeg: %s },"
            % (
                json_str(src),
                image.width,
                image.height,
                js_sources(line_sources["avif"]),
                js_sources(line_sources["webp"]),
                js_sources(line_sources["jpeg"]),
            )
        )
        print(f"{src} {image.size} worst<= {worst}")
    body = "\n".join(entries)
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST.write_text(
        """// Generated by scripts/optimize-feed-images.py. Do not edit by hand.
import type { FeedEntry } from "./feed-image.ts";

export const FEED_MANIFEST: Record<string, FeedEntry> = {
%s
};
"""
        % body,
        encoding="utf-8",
    )
    print(f"photos {len(photos)} worst {worst}")


if __name__ == "__main__":
    main()
