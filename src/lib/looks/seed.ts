import { EDITORIAL_USER_ID, type Look, type ProductOffer, type ProductTag } from "./types";

const EUR = "EUR";

function offer(
  id: string,
  retailerId: string,
  price: string,
  url: string,
): ProductOffer {
  return { id, retailerId, price, currency: EUR, url };
}

function tag(
  base: Omit<ProductTag, "currency" | "offers"> & {
    offers: ProductOffer[];
    wornUrl: string;
    wornRetailerId: string;
  },
): ProductTag {
  const priced = base.offers.filter((item) => Number.parseFloat(item.price) > 0);
  const lowest = priced.reduce(
    (best, item) => (Number.parseFloat(item.price) < Number.parseFloat(best.price) ? item : best),
    priced[0] ?? base.offers[0],
  );
  return {
    ...base,
    currency: EUR,
    url: lowest?.url ?? base.url,
    price: lowest?.price ?? "",
    retailerId: lowest?.retailerId ?? base.wornRetailerId,
    offers: base.offers,
    wornUrl: base.wornUrl,
    wornRetailerId: base.wornRetailerId,
  };
}

function worn(
  id: string,
  x: number,
  y: number,
  name: string,
  brand: string,
  price: string,
  url: string,
  retailerId: string,
): ProductTag {
  return tag({
    id,
    x,
    y,
    name,
    brand,
    price,
    url,
    retailerId,
    wornUrl: url,
    wornRetailerId: retailerId,
    offers: [offer(`${id}-live`, retailerId, price, url)],
  });
}

